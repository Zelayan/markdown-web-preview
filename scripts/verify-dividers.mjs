import { chromium } from 'playwright';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const { createPrintHtml } = createRequire(import.meta.url)('../vscode/print-html.cjs');
const browser = await chromium.launch({ headless: true, ...(process.env.MWP_CHROME_EXECUTABLE ? { executablePath: process.env.MWP_CHROME_EXECUTABLE } : {}) });
try {
  const directory = await mkdtemp(join(tmpdir(), 'mwp-divider-qa-'));
  const entry = join(directory, 'index.html');
  await writeFile(entry, `<!doctype html><html><head><meta charset="utf-8"><style>html,body,#root{height:100%;margin:0}</style></head><body><div id="root"></div><script>window.messages=[];window.acquireVsCodeApi=()=>({getState:()=>null,setState:()=>{},postMessage:m=>window.messages.push(m)})</script><script src="${pathToFileURL(resolve('vscode/webview.js')).href}"></script></body></html>`);
  const page = await browser.newPage({ viewport: { width: 1100, height: 760 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(entry).href);
  const text = '# 文档章节分隔\n\n这是一条安静的分隔线，不跟随强调色，不使用渐变或阴影。\n\n---\n\n## 配置与验证\n\n分隔线与正文同宽；浅色和深色模式保持低对比度灰色。\n\n---\n\n标准二级标题\n---\n\n上面仍然是二级标题，不会误改为分隔线。\n\n```text\n---\n```';
  await page.evaluate(text => window.dispatchEvent(new MessageEvent('message', { data: { type: 'document', text, dark: false, resourceBase: 'https://webview.test/' } })), text);
  await page.locator('.mwp-prose hr').first().waitFor();
  const inspect = () => page.locator('.mwp-prose hr').first().evaluate(el => { const s = getComputedStyle(el); return { color: s.borderTopColor, width: s.borderTopWidth, margin: s.marginTop, shadow: s.boxShadow }; });
  assert.equal(await page.locator('.mwp-prose hr').count(), 2);
  const light = await inspect();
  assert.ok(Math.abs(parseFloat(light.width) - 1) < 0.1); assert.equal(light.margin, '24px'); assert.equal(light.shadow, 'none');
  await page.screenshot({ path: join(directory, 'light.png') });
  await page.getByTitle(/切换界面主题/).click();
  await page.waitForFunction(color => getComputedStyle(document.querySelector('.mwp-prose hr')).borderTopColor !== color, light.color);
  const dark = await inspect(); assert.ok(Math.abs(parseFloat(dark.width) - 1) < 0.1);
  await page.screenshot({ path: join(directory, 'dark.png') });
  await page.getByRole('button', { name: '导出 PDF' }).click();
  const exported = await page.evaluate(() => window.messages.find(m => m.type === 'exportPdf'));
  const paper = await browser.newPage();
  await paper.setContent(createPrintHtml(exported.html, 'Divider QA', 'test', { accent: '#dc2626' }));
  await paper.emulateMedia({ media: 'print' });
  const print = await paper.locator('hr').first().evaluate(el => { const s = getComputedStyle(el); return [s.borderTopWidth, s.borderTopColor, s.marginTop]; });
  assert.deepEqual(print, ['1px', 'rgb(229, 231, 235)', '24px']);
  await paper.pdf({ path: join(directory, 'dividers.pdf'), preferCSSPageSize: true, printBackground: true });
  assert.deepEqual(errors, []);
  console.log(`Divider browser QA passed: light ${light.color}, dark ${dark.color}, paper neutral; artifacts ${directory}`);
} finally { await browser.close(); }
